-- Abone / hat / tarife / siparis semasi (Oracle 23ai Free)

CREATE SEQUENCE SEQ_ABONE START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE SEQ_HAT START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE SEQ_SIPARIS START WITH 1 INCREMENT BY 20;
CREATE SEQUENCE SEQ_FATURA_KALEMI START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_KULLANIM START WITH 1 INCREMENT BY 1;

CREATE TABLE TARIFE (
    ID           NUMBER(10)    NOT NULL,
    KOD          VARCHAR2(20)  NOT NULL,
    AD           VARCHAR2(100) NOT NULL,
    AYLIK_UCRET  NUMBER(10,2)  NOT NULL,
    DATA_MB      NUMBER(10)    NOT NULL,
    DAKIKA       NUMBER(10)    NOT NULL,
    AKTIF        CHAR(1)       DEFAULT 'E' NOT NULL,
    CONSTRAINT PK_TARIFE PRIMARY KEY (ID),
    CONSTRAINT UK_TARIFE_KOD UNIQUE (KOD),
    CONSTRAINT CK_TARIFE_AKTIF CHECK (AKTIF IN ('E', 'H')),
    CONSTRAINT CK_TARIFE_UCRET CHECK (AYLIK_UCRET >= 0)
);

CREATE TABLE ABONE (
    ID         NUMBER(19)    NOT NULL,
    TCKN       VARCHAR2(11)  NOT NULL,
    AD_SOYAD   VARCHAR2(120) NOT NULL,
    OLUSTURMA  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ABONE PRIMARY KEY (ID),
    CONSTRAINT UK_ABONE_TCKN UNIQUE (TCKN)
);

-- KOTA_MB: icinde bulunulan donem icin tanimlanan data kotasi (kist + devreden)
-- KOTA_BASLANGIC: kotanin gecerli oldugu an; bu andan onceki kullanim dusulmez
CREATE TABLE HAT (
    ID                 NUMBER(19)   NOT NULL,
    MSISDN             VARCHAR2(12) NOT NULL,
    ABONE_ID           NUMBER(19)   NOT NULL,
    TARIFE_ID          NUMBER(10)   NOT NULL,
    DURUM              VARCHAR2(10) NOT NULL,
    AKTIVASYON_TARIHI  DATE,
    KOTA_MB            NUMBER(12,2) DEFAULT 0 NOT NULL,
    KOTA_BASLANGIC     TIMESTAMP,
    VERSIYON           NUMBER(10)   DEFAULT 0 NOT NULL,
    CONSTRAINT PK_HAT PRIMARY KEY (ID),
    CONSTRAINT UK_HAT_MSISDN UNIQUE (MSISDN),
    CONSTRAINT FK_HAT_ABONE FOREIGN KEY (ABONE_ID) REFERENCES ABONE (ID),
    CONSTRAINT FK_HAT_TARIFE FOREIGN KEY (TARIFE_ID) REFERENCES TARIFE (ID),
    CONSTRAINT CK_HAT_DURUM CHECK (DURUM IN ('BEKLEMEDE', 'AKTIF', 'ASKIDA', 'KAPALI')),
    CONSTRAINT CK_HAT_MSISDN CHECK (REGEXP_LIKE(MSISDN, '^905[0-9]{9}$'))
);
CREATE INDEX IX_HAT_ABONE ON HAT (ABONE_ID);

CREATE TABLE KULLANIM (
    ID            NUMBER(19)   NOT NULL,
    HAT_ID        NUMBER(19)   NOT NULL,
    DATA_MB       NUMBER(12,2) NOT NULL,
    KAYIT_ZAMANI  TIMESTAMP    NOT NULL,
    CONSTRAINT PK_KULLANIM PRIMARY KEY (ID),
    CONSTRAINT FK_KULLANIM_HAT FOREIGN KEY (HAT_ID) REFERENCES HAT (ID),
    CONSTRAINT CK_KULLANIM_MB CHECK (DATA_MB > 0)
);
CREATE INDEX IX_KULLANIM_HAT_ZAMAN ON KULLANIM (HAT_ID, KAYIT_ZAMANI);

CREATE TABLE FATURA_KALEMI (
    ID         NUMBER(19)    NOT NULL,
    HAT_ID     NUMBER(19)    NOT NULL,
    DONEM      CHAR(7)       NOT NULL,
    ACIKLAMA   VARCHAR2(200) NOT NULL,
    TUTAR      NUMBER(12,2)  NOT NULL,
    OLUSTURMA  TIMESTAMP     NOT NULL,
    CONSTRAINT PK_FATURA_KALEMI PRIMARY KEY (ID),
    CONSTRAINT FK_FATURA_HAT FOREIGN KEY (HAT_ID) REFERENCES HAT (ID)
);
CREATE INDEX IX_FATURA_HAT_DONEM ON FATURA_KALEMI (HAT_ID, DONEM);

CREATE TABLE SIPARIS (
    ID               NUMBER(19)    NOT NULL,
    ISTEMCI_REF      VARCHAR2(64)  NOT NULL,
    TIP              VARCHAR2(20)  NOT NULL,
    HAT_ID           NUMBER(19)    NOT NULL,
    HEDEF_TARIFE_ID  NUMBER(10),
    DURUM            VARCHAR2(12)  NOT NULL,
    KANAL            VARCHAR2(8)   NOT NULL,
    HATA_MESAJI      VARCHAR2(400),
    KIST_UCRET       NUMBER(12,2),
    DEVREDEN_MB      NUMBER(12,2),
    OLUSTURMA        TIMESTAMP     NOT NULL,
    TAMAMLANMA       TIMESTAMP,
    CONSTRAINT PK_SIPARIS PRIMARY KEY (ID),
    -- ayni istemci referansiyla gelen tekrar istekleri tek siparise indirger
    CONSTRAINT UK_SIPARIS_ISTEMCI_REF UNIQUE (ISTEMCI_REF),
    CONSTRAINT FK_SIPARIS_HAT FOREIGN KEY (HAT_ID) REFERENCES HAT (ID),
    CONSTRAINT FK_SIPARIS_TARIFE FOREIGN KEY (HEDEF_TARIFE_ID) REFERENCES TARIFE (ID),
    CONSTRAINT CK_SIPARIS_TIP CHECK (TIP IN ('AKTIVASYON', 'TARIFE_DEGISIKLIGI')),
    CONSTRAINT CK_SIPARIS_DURUM CHECK (DURUM IN ('ALINDI', 'TAMAMLANDI', 'REDDEDILDI')),
    CONSTRAINT CK_SIPARIS_KANAL CHECK (KANAL IN ('REST', 'SOAP', 'JSF'))
);
CREATE INDEX IX_SIPARIS_HAT ON SIPARIS (HAT_ID);
CREATE INDEX IX_SIPARIS_OLUSTURMA ON SIPARIS (OLUSTURMA DESC);
